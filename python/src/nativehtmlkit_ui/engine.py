"""NativeHTMLKit UI document owner, DOM scheduler, and scoped components.

Uses public `Application.open_html`, `Document.on`, `Document.batch`, and
Document DOM methods exclusively. It never imports Core or SDK internals.
"""
from __future__ import annotations

from contextlib import contextmanager
from dataclasses import dataclass, field
from html import escape
from importlib.resources import files
from pathlib import Path
from queue import Full, Queue, Empty
from threading import Event, Lock, Thread, current_thread
import logging
import re
import uuid
import weakref
from typing import Any, Callable, Iterable

from .reactive import Binding, State, Observable, _MISSING

LOG = logging.getLogger(__name__)
_ID = re.compile(r"^[A-Za-z][A-Za-z0-9_:\-.]*$")
_ATTR = re.compile(r"^[A-Za-z_:][A-Za-z0-9_:.-]*$")
_STOP = object()
_UNSET = object()


def _string(value: Any) -> str:
    return "" if value is None else str(value)


def _attr(name: str, value: Any) -> str:
    if not _ATTR.fullmatch(name) or name.lower().startswith("on"):
        raise ValueError(f"Unsafe HTML attribute name: {name!r}")
    if value is None or value is False:
        return ""
    if value is True:
        return f" {name}"
    return f' {name}="{escape(_string(value), quote=True)}"'


@dataclass(eq=False)
class Element:
    tag: str
    id: str
    attrs: dict[str, Any] = field(default_factory=dict)
    children: list["Element | str"] = field(default_factory=list)
    bindings: list[tuple[str, Binding, str | None]] = field(default_factory=list)

    def html(self) -> str:
        attrs = dict(self.attrs)
        attrs["id"] = self.id
        start = "<" + self.tag + "".join(_attr(k, v) for k, v in attrs.items()) + ">"
        if self.tag in {"input", "img", "hr", "br"}:
            return start  # HTML void tag
        return start + "".join(x.html() if isinstance(x, Element) else escape(x, quote=False)
                               for x in self.children) + f"</{self.tag}>"


class UI:
    """UI builder; construct on the main thread, then mount into a connected SDK app.

    The owner is one lightweight thread per UI window. SDK event workers only
    enqueue events and do not block on DOM RPC. All runtime DOM writes happen
    on the UI owner, except the initial document load during mount.
    """
    def __init__(self, *, title: str = "NativeHTMLKit UI", width: int = 940,
                 height: int = 660, theme: str = "cobalt", density: str = "compact",
                 extra_css: str = ""):
        if theme not in ("cobalt", "graphite", "daylight"):
            raise ValueError("theme must be cobalt, graphite or daylight")
        if density not in ("compact", "regular", "comfortable"):
            raise ValueError("density must be compact, regular or comfortable")
        self.title, self.width, self.height = title, width, height
        self.theme, self.density, self.extra_css = theme, density, extra_css
        self.prefix = "nhkui-" + uuid.uuid4().hex[:12]
        self._index = 0
        self.root = Element("main", self._id(), {"class": "nhk-app"})
        self._stack = [self.root]
        self._bindings: list[tuple[Element, str, Binding, str | None]] = []
        self._actions: dict[str, dict[str, Callable[[dict], None]]] = {}
        self._subscriptions: list[Callable[[], None]] = []
        self._closed = False
        self._lock = Lock()
        self._dirty: set[Binding] = set()
        self._scheduled = False
        self._work: Queue = Queue(maxsize=4096)
        self._thread: Thread | None = None
        self._ready = Event()
        self._errors: list[str] = []
        self._dropped = 0
        self._poisoned = False  # A failed DOM transaction leaves the managed DOM uncertain.
        self.window: Any = None
        self.document: Any = None
        self.app: Any = None
        self._updates = 0
        self._operations = 0

    def _id(self) -> str:
        self._index += 1
        return f"{self.prefix}-{self._index}"

    def element(self, tag: str, *, css_class: str = "", attrs: dict[str, Any] | None = None,
                text: str | State | Callable[[], Any] | None = None) -> Element:
        if tag not in {"div", "section", "main", "header", "footer", "article", "nav", "aside", "p",
                       "span", "h1", "h2", "h3", "h4", "small", "strong", "em", "button", "label",
                       "input", "select", "option", "textarea", "form", "ul", "li", "table", "thead",
                       "tbody", "tr", "th", "td", "dialog", "pre", "code", "hr"}:
            raise ValueError(f"Use raw_html for unsupported tag {tag!r} (trusted content only)")
        if self.document is not None or self._closed:
            raise RuntimeError("Cannot add components after mount/disposal")
        a = dict(attrs or {})
        if "id" in a:
            raise ValueError("Managed UI element ids are generated by the library")
        if css_class:
            a["class"] = (a.get("class", "") + " " + css_class).strip()
        el = Element(tag, self._id(), a)
        self._stack[-1].children.append(el)
        if text is not None:
            if isinstance(text, Observable) or callable(text):
                bind = self._bind(el, "text", text)
                el.children.append(_string(bind.last))
            else:
                el.children.append(_string(text))
        return el

    def _bind(self, el: Element, kind: str, value: State | Callable[[], Any], name: str | None = None) -> Binding:
        expr = (lambda: value.value) if isinstance(value, Observable) else value
        bind = Binding(expr, self._mark_dirty)
        bind.last = bind.evaluate()
        self._bindings.append((el, kind, bind, name))
        el.bindings.append((kind, bind, name))
        return bind

    @contextmanager
    def container(self, tag: str = "div", *, css_class: str = "", attrs: dict[str, Any] | None = None):
        if self.document is not None:
            raise RuntimeError("UI tree already mounted; use state bindings to update it")
        node = self.element(tag, css_class=css_class, attrs=attrs)
        self._stack.append(node)
        try:
            yield node
        finally:
            self._stack.pop()

    def row(self):
        return self.container(css_class="nhk-row")

    def column(self):
        return self.container(css_class="nhk-col")

    def grid(self):
        return self.container(css_class="nhk-grid")

    def card(self):
        return self.container(css_class="nhk-card")

    def stack(self):
        return self.container(css_class="nhk-stack")

    def heading(self, value: str | State | Callable[[], Any], *, level: int = 2) -> Element:
        if level not in (1, 2, 3, 4):
            raise ValueError("heading level must be 1 through 4")
        return self.element(f"h{level}", css_class="nhk-heading", text=value)

    def text(self, value: str | State | Callable[[], Any], *, muted: bool = False) -> Element:
        return self.element("p", css_class="nhk-text" + (" nhk-muted" if muted else ""), text=value)

    def badge(self, value: str | State | Callable[[], Any]) -> Element:
        return self.element("span", css_class="nhk-badge", text=value)

    def alert(self, value: str | State | Callable[[], Any]) -> Element:
        return self.element("div", css_class="nhk-alert", attrs={"role": "status"}, text=value)

    def button(self, label: str | State | Callable[[], Any], *, on_click: Callable[[dict], None] | None = None,
               variant: str = "primary", disabled: bool | State | Callable[[], bool] = False) -> Element:
        if variant not in ("primary", "secondary", "danger", "quiet"):
            raise ValueError("Unsupported button variant")
        el = self.element("button", css_class=f"nhk-button nhk-{variant}",
                          attrs={"type": "button"}, text=label)
        self._boolean_attr(el, "disabled", disabled)
        if on_click is not None:
            self.on(el, "click", on_click)
        return el

    def input(self, value: State[str], *, label: str = "", placeholder: str = "",
              kind: str = "text") -> Element:
        if kind not in ("text", "password", "search", "email", "number"):
            raise ValueError("Unsupported input type")
        if label:
            # Native label is linked to a generated element id, never placeholder-only.
            with self.container(css_class="nhk-field"):
                return self._input_control(value, label, placeholder, kind)
        return self._input_control(value, label, placeholder, kind)

    def _input_control(self, value: State[str], label: str, placeholder: str, kind: str) -> Element:
        el = self.element("input", css_class="nhk-input",
                          attrs={"type": kind, "placeholder": placeholder})
        if label:
            self._label_before(el, label)
        self._value_binding(el, value, "value", "input")
        return el

    def _label_before(self, control: Element, text: str) -> Element:
        """Add a native <label for> that precedes its control in document (reading) order."""
        label = self.element("label", css_class="nhk-label", attrs={"for": control.id}, text=text)
        siblings = self._stack[-1].children
        siblings.remove(label)
        siblings.insert(siblings.index(control), label)
        return label

    def checkbox(self, value: State[bool], *, label: str) -> Element:
        with self.container("div", css_class="nhk-checkrow"):
            el = self.element("input", attrs={"type": "checkbox"}, css_class="nhk-checkbox")
            self.element("label", attrs={"for": el.id}, text=label)
        self._value_binding(el, value, "checked", "change")
        return el

    def select(self, value: State[str], choices: Iterable[tuple[str, str]], *, label: str = "") -> Element:
        with self.container(css_class="nhk-field"):
            el = self.element("select", css_class="nhk-select")
            if label:
                self._label_before(el, label)
            for key, text in choices:
                child = Element("option", self._id(), {"value": str(key)})
                child.children.append(str(text))
                el.children.append(child)
            self._value_binding(el, value, "value", "change")
            # A <select> has no value attribute: mark the bound option as selected instead.
            el.attrs.pop("value", None)
            for child in el.children:
                if isinstance(child, Element) and child.attrs.get("value") == _string(value.value):
                    child.attrs["selected"] = True
        return el

    def _value_binding(self, el: Element, value: State, kind: str, event: str) -> None:
        if not isinstance(value, State):
            raise TypeError("Two-way controls require a State instance")
        bind = self._bind(el, kind, value)
        el.attrs[kind] = bind.last  # checked False is omitted

        def receive(payload: dict) -> None:
            # Event value/checked is authoritative; native editor already committed it.
            if kind not in payload:
                # SDK may omit it on some event types; use explicit public getter.
                current = (self.document.get_value(el.id) if kind == "value" else
                           self.document.get_checked(el.id))
            else:
                current = payload[kind]
            if kind == "checked":
                current = bool(current)
            else:
                current = _string(current)
            bind.last = current  # prevent an echo write from resetting selection/IME
            value.set(current)
        self.on(el, event, receive)

    def _boolean_attr(self, el: Element, name: str, value: bool | State | Callable[[], bool]) -> None:
        if isinstance(value, Observable) or callable(value):
            bind = self._bind(el, "boolean", value, name)
            if bind.last:
                el.attrs[name] = True
        elif value:
            el.attrs[name] = True

    def when(self, condition: State | Callable[[], bool]):
        """Show/hide a permanently mounted subtree; never rebuild active native inputs."""
        @contextmanager
        def region():
            with self.container(css_class="nhk-region") as el:
                b = self._bind(el, "visible", condition)
                if not bool(b.last):
                    el.attrs["class"] += " nhk-hidden"
                yield el
        return region()

    def text_list(self, values: State | Callable[[], Iterable[Any]],
                  *, formatter: Callable[[Any], str] = str) -> Element:
        """Bound text-only list. Replaces this region when changed (not a virtualized grid)."""
        el = self.element("ul", css_class="nhk-list")
        expr = lambda: tuple(formatter(item) for item in
                             (values.value if isinstance(values, Observable) else values()))
        self._bind(el, "html", expr)  # _render_el renders the escaped items of this binding
        return el

    def on(self, el: Element, kind: str, callback: Callable[[dict], None]) -> None:
        if kind not in ("click", "input", "change", "keydown", "submit", "auxclick", "contextmenu"):
            raise ValueError(f"Unsupported event type: {kind!r}")
        self._actions.setdefault(kind, {})[el.id] = callback

    def raw_html(self, markup: str) -> Element:
        """Trusted HTML only; no sanitization. Do not pass remote/user content."""
        el = self.element("div", css_class="nhk-custom")
        # Plain strings elsewhere are escaped; only this explicit method inserts raw markup.
        setattr(el, "_trusted_html", markup)
        return el

    def _render_el(self, el: Element) -> str:
        attrs = dict(el.attrs)
        attrs["id"] = el.id
        start = "<" + el.tag + "".join(_attr(k, v) for k, v in attrs.items()) + ">"
        if el.tag == "input":
            return start
        if hasattr(el, "_trusted_html"):
            body = getattr(el, "_trusted_html")
        elif any(k == "html" for k, _, _ in el.bindings):
            bind = next(b for kind, b, _ in el.bindings if kind == "html")
            body = self._render_text_list(bind.last)
        else:
            body = "".join(self._render_el(x) if isinstance(x, Element) else escape(x, quote=False)
                           for x in el.children)
        return start + body + f"</{el.tag}>"

    @staticmethod
    def _render_text_list(items: Iterable[Any]) -> str:
        return "".join("<li>" + escape(_string(v), quote=False) + "</li>" for v in items)

    @staticmethod
    def _css() -> str:
        return files("nativehtmlkit_ui.assets").joinpath("ui.css").read_text(encoding="utf-8")

    def html(self) -> str:
        if len(self._stack) != 1:
            raise RuntimeError("An open container context is not closed")
        body = self._render_el(self.root)
        theme = escape(self.theme, quote=True)
        density = escape(self.density, quote=True)
        return ("<!doctype html><html lang='en'><head><meta charset='utf-8'>"
                "<meta name='viewport' content='width=device-width, initial-scale=1'>"
                "<title>" + escape(self.title) + "</title><style>" + self._css() + "\n" + self.extra_css +
                "</style></head><body class='nhk-theme-" + theme + " nhk-density-" + density + "'>" +
                body + "</body></html>")

    def mount(self, app: Any) -> "UI":
        if self.document is not None:
            raise RuntimeError("UI already mounted")
        if self._closed:
            raise RuntimeError("UI already disposed")
        markup = self.html()
        self.app = app
        self.window = app.open_html(markup, title=self.title, width=self.width, height=self.height)
        try:
            self.document = self.window.document
            # Native control values initialize from HTML attrs; make the live control state explicit.
            for el, kind, b, _ in self._bindings:
                if kind == "value":
                    self.document.set_value(el.id, _string(b.last))
                elif kind == "checked":
                    self.document.set_checked(el.id, bool(b.last))
            for kind in self._actions:
                # One subscription per event kind instead of one per managed component.
                unsub = self.document.on(kind, lambda ev, k=kind: self._forward_event(k, ev))
                self._subscriptions.append(unsub)
            # Application.on_shutdown has no unsubscribe: hold this UI weakly so repeated
            # mount/dispose cycles do not keep disposed UIs (and their trees) alive.
            app.on_shutdown(_weak_call(self, "dispose"))
            window_id = self.window.id
            ref = weakref.ref(self)

            def window_event(ev: dict) -> None:
                ui = ref()
                if ui is not None and ev.get("window_id") == window_id and ev.get("type") == "closed":
                    ui.dispose()
            self._subscriptions.append(app.on_window_event(window_event))
            self._thread = Thread(target=self._owner, name="nativehtmlkit-ui", daemon=True)
            self._thread.start()
        except BaseException:
            # Do not leave a half-mounted UI behind; the caller still owns the SDK lifecycle.
            self.dispose()
            try:
                self.window.request_close()
            except Exception:
                LOG.debug("Could not close the window of a failed mount", exc_info=True)
            raise
        with self._lock:
            pending = bool(self._dirty)
        if pending:
            self._queue_flush()
        return self

    def _owner(self) -> None:
        self._ready.set()
        while True:
            item = self._work.get()
            if item is _STOP:
                return
            fn, args = item
            if self._closed:
                continue
            try:
                fn(*args)
            except Exception as exc:
                self._record_error(exc)

    def _record_error(self, exc: Exception) -> None:
        LOG.exception("NativeHTMLKit UI callback/update failed")
        with self._lock:
            self._errors.append(f"{type(exc).__name__}: {exc}")
            self._errors[:] = self._errors[-64:]

    @property
    def diagnostics(self) -> dict[str, Any]:
        with self._lock:
            return {"errors": tuple(self._errors), "event_queue_dropped": self._dropped,
                    "pending_updates": len(self._dirty), "dom_uncertain": self._poisoned,
                    "updates": self._updates, "operations": self._operations,
                    "subscriptions": len(self._subscriptions), "disposed": self._closed}

    def post(self, fn: Callable, *args: Any) -> None:
        if self._closed:
            return
        # Even on the owner, queue rather than invoke immediately. This preserves
        # batching across multiple changes in a single event callback.
        try:
            self._work.put_nowait((fn, args))
        except Full:
            with self._lock:
                self._dropped += 1
            raise RuntimeError("NativeHTMLKit UI queue full: event not delivered; inspect diagnostics")

    def _forward_event(self, kind: str, event: dict) -> None:
        """Runs on the SDK event worker: only enqueue, never block or raise into the SDK."""
        if self._closed:
            return
        try:
            self._work.put_nowait((self._event, (kind, event)))
        except Full:
            with self._lock:
                self._dropped += 1
                first = self._dropped == 1
            # Do not reconstruct the lost event; report it once per UI and count every loss.
            (LOG.error if first else LOG.debug)(
                "NativeHTMLKit UI event queue full: a %s event was dropped (total %d)", kind, self._dropped)

    def _event(self, kind: str, event: dict) -> None:
        actions = self._actions.get(kind, {})
        path = [event.get("element"), *(event.get("path") or [])]
        for id_ in path:
            fn = actions.get(id_)
            if fn is not None:
                fn(event)
                break  # nearest registered ancestor, like a delegated native handler

    def _mark_dirty(self, bind: Binding) -> None:
        with self._lock:
            if self._closed:
                return
            self._dirty.add(bind)
        if self.document is not None:
            self._queue_flush()

    def _queue_flush(self) -> None:
        with self._lock:
            if self._closed or self._scheduled:
                return
            self._scheduled = True
        try:
            self.post(self._flush)
        except Exception:
            with self._lock:
                self._scheduled = False
            raise

    def _flush(self) -> None:
        with self._lock:
            dirty = self._dirty
            self._dirty = set()
            self._scheduled = False
        if not dirty or self._closed or self.document is None or self._poisoned:
            return
        if self._document_gone():
            self.dispose()
            return
        operations: list[dict] = []
        special: list[tuple[str, str, Any]] = []
        for el, kind, bind, name in self._bindings:
            if bind not in dirty or bind.closed:
                continue
            current = bind.evaluate()
            if current is bind.last or current == bind.last:
                continue
            bind.last = current
            if kind == "text":
                operations.append({"op": "set_text", "element": el.id, "text": _string(current)})
            elif kind == "visible":
                operations.append({"op": "remove_class" if current else "add_class",
                                   "element": el.id, "name": "nhk-hidden"})
            elif kind == "boolean":
                operations.append({"op": "set_attribute" if current else "remove_attribute",
                                   "element": el.id, "name": name, **({"value": ""} if current else {})})
            elif kind in ("value", "checked", "html"):
                special.append((kind, el.id, current))
        for kind, ident, value in special:
            if kind == "html":
                operations.append({"op": "replace_children_html", "element": ident,
                                   "html": self._render_text_list(value)})
        special = [entry for entry in special if entry[0] != "html"]
        if not operations and not special:
            return
        # Do not silently recover a failed atomic batch or an outcome-unknown write; the DOM may be stale.
        try:
            for start in range(0, len(operations), 128):
                batch = operations[start:start + 128]
                if len(batch) == 1:
                    op = batch[0]
                    self.document.command(op["op"], **{k: v for k, v in op.items() if k != "op"})
                else:
                    self.document.batch(batch)
                self._operations += len(batch)
            for kind, ident, value in special:
                if kind == "value":
                    self.document.set_value(ident, _string(value))
                else:
                    self.document.set_checked(ident, bool(value))
                self._operations += 1
            self._updates += 1
        except Exception as exc:
            if self._document_gone(exc):
                # The window closed or the app shut down: nothing left to keep in sync.
                LOG.debug("NativeHTMLKit UI document is gone; disposing the UI")
                self.dispose()
                return
            with self._lock:
                self._poisoned = True
            raise

    def _document_gone(self, exc: BaseException | None = None) -> bool:
        """True when the SDK retired this UI's window/document (closed, replaced, app.shutdown)."""
        window = self.window
        if window is None or getattr(window, "closed", False) or getattr(window, "document", None) is not self.document:
            return True
        return exc is not None and type(exc).__name__ in ("StaleDocumentError", "ApplicationShutdownError")

    def sync(self, timeout: float = 10.0) -> None:
        """Drain work submitted before this call (for tests/explicit synchronization)."""
        if self._closed:
            raise RuntimeError("UI already disposed")
        if self._thread is None:
            raise RuntimeError("UI not mounted")
        if current_thread() is self._thread:
            self._flush()
            return
        marker = Event()
        self.post(lambda: marker.set())
        if not marker.wait(timeout):
            raise TimeoutError("UI owner did not process the synchronization marker")
        if self._poisoned:
            raise RuntimeError("NativeHTMLKit UI DOM state is uncertain after a failed operation; inspect diagnostics")

    def dispose(self) -> None:
        with self._lock:
            if self._closed:
                return
            self._closed = True
        for unsubscribe in self._subscriptions:
            try:
                unsubscribe()
            except Exception:
                LOG.exception("Failed to unsubscribe a native event")
        self._subscriptions.clear()
        for _, _, bind, _ in self._bindings:
            bind.close()
        try:
            self._work.put_nowait(_STOP)
        except Full:
            # A bounded queue can be full during shutdown; make room for the stop token.
            try:
                self._work.get_nowait()
                self._work.put_nowait(_STOP)
            except Empty:
                pass
        if self._thread is not None and current_thread() is not self._thread:
            self._thread.join(timeout=2.0)

    close = dispose


def _weak_call(obj: Any, method: str) -> Callable[[], None]:
    ref = weakref.ref(obj)

    def call() -> None:
        target = ref()
        if target is not None:
            getattr(target, method)()
    return call
